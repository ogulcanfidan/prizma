let currentLang = "tr";

function detectLanguage() {
  try {
    const nav = (navigator.language || navigator.userLanguage || "").toLowerCase();
    const code = nav.slice(0, 2);
    if (SUPPORTED_LANGS.includes(code)) return code;
  } catch (e) {
    /* navigator yok/erişilemedi — yoksay */
  }
  return "en"; // uluslararası varsayılan (algılanamazsa/desteklenmezse)
}

function applyDocumentDirection() {
  try {
    document.documentElement.setAttribute("lang", currentLang);
    document.documentElement.setAttribute("dir", RTL_LANGS.has(currentLang) ? "rtl" : "ltr");
  } catch (e) {
    /* DOM henüz hazır değil — yoksay */
  }
}

// Uygulama başlarken BİR KEZ çağrılır (main.js). GameState.settings.language
// "auto" ise cihaz dilini algılar, aksi halde kullanıcının elle seçtiği dili
// kullanır (bkz. setLanguage).
export function initI18n() {
  const saved = GameState.settings.language;
  currentLang = saved && saved !== "auto" && SUPPORTED_LANGS.includes(saved) ? saved : detectLanguage();
  applyDocumentDirection();
}

export function getLanguage() {
  return currentLang;
}

// code: desteklenen bir dil kodu YA DA "auto" (tekrar cihaz diline dön).
export function setLanguage(code) {
  GameState.updateSettings({ language: code });
  currentLang = code === "auto" ? detectLanguage() : code;
  applyDocumentDirection();
}

export function t(key, vars) {
  const dict = STRINGS[currentLang] || STRINGS.en;
  let str = dict[key];
  if (str === undefined) str = STRINGS.tr[key];
  if (str === undefined) return key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
    }
  }
  return str;
}
